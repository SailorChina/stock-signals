def get_stock_info(code: str) -> dict:
    """查询股票信息，返回 {name, sector, desc}，找不到返回空dict"""
    info = STOCK_INFO.get(code, {})
    if info:
        return info
    # 尝试不带前缀的匹配（如 NVDA -> US.NVDA）
    parts = code.split(".")
    if len(parts) == 2:
        market, ticker = parts
        alt = f"{market}.{ticker}"
        return STOCK_INFO.get(alt, {})
    return {}
